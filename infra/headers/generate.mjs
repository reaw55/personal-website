#!/usr/bin/env node
// Prints, or writes into place, the security-header config for one host.
//
//   node infra/headers/generate.mjs <host> [options]
//
//   host        cloudflare | netlify | vercel | nginx | caddy
//   --enforce   send an enforcing Content-Security-Policy
//               (default: Report-Only, which blocks nothing)
//   --relay=URL origin of the contact relay, added to connect-src
//   --turnstile allow Cloudflare Turnstile
//   --write     cloudflare/netlify: write personal-website/public/_headers
//               vercel:             write personal-website/vercel.json
//               (nginx and caddy always print; paste into the server config)
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { buildSecurityHeaders, cacheRules } from "./policy.mjs";

const HOSTS = ["cloudflare", "netlify", "vercel", "nginx", "caddy"];
const args = process.argv.slice(2);
const host = args.find((a) => !a.startsWith("--"));
const flag = (name) => args.includes(`--${name}`);
const option = (name) => args.find((a) => a.startsWith(`--${name}=`))?.split("=").slice(1).join("=");

function fail(message) {
  console.error(`${message}\n\nUsage: node infra/headers/generate.mjs <${HOSTS.join("|")}> [--enforce] [--relay=https://…] [--turnstile] [--write]`);
  process.exit(1);
}
if (!HOSTS.includes(host)) fail(host ? `Unknown host "${host}".` : "Missing host.");

let relayOrigin;
if (option("relay")) {
  let url;
  try {
    url = new URL(option("relay"));
  } catch {
    fail(`--relay is not a URL: ${option("relay")}`);
  }
  if (url.protocol !== "https:") fail("--relay must be an https:// URL.");
  relayOrigin = url.origin;
}

const headers = buildSecurityHeaders({ enforce: flag("enforce"), relayOrigin, turnstile: flag("turnstile") });
const entries = Object.entries(headers);
const mode = flag("enforce") ? "enforcing" : "Report-Only (nothing is blocked yet)";
const stamp = `Generated by infra/headers/generate.mjs. CSP mode: ${mode}. Edit infra/headers/policy.mjs and regenerate; do not edit by hand.`;

const formats = {
  // Cloudflare Pages and Netlify share the _headers format. Both already
  // revalidate HTML, so only the long-lived paths need a cache rule.
  _headers: () =>
    [
      `# ${stamp}`,
      "/*",
      ...entries.map(([name, value]) => `  ${name}: ${value}`),
      "/assets/*",
      `  Cache-Control: ${cacheRules.assets}`,
      "/images/*",
      `  Cache-Control: ${cacheRules.images}`,
      "",
    ].join("\n"),

  vercel: () =>
    JSON.stringify(
      {
        headers: [
          { source: "/(.*)", headers: entries.map(([key, value]) => ({ key, value })) },
          { source: "/assets/(.*)", headers: [{ key: "Cache-Control", value: cacheRules.assets }] },
          { source: "/images/(.*)", headers: [{ key: "Cache-Control", value: cacheRules.images }] },
        ],
      },
      null,
      2,
    ) + "\n",

  // nginx drops inherited add_header lines in any block that sets its own,
  // so the security headers live in a snippet that every location includes.
  nginx: () =>
    [
      `# ${stamp}`,
      "#",
      "# 1. Save this first part as /etc/nginx/snippets/portfolio-security-headers.conf",
      ...entries.map(([name, value]) => `add_header ${name} "${value}" always;`),
      "",
      "# 2. Use it in the site's server block (adjust server_name, root and TLS):",
      "#",
      "# server {",
      "#   listen 443 ssl;",
      "#   server_name SITE_DOMAIN;",
      "#   root /var/www/personal-website/dist;",
      "#   index index.html;",
      "#",
      "#   location /assets/ {",
      "#     include snippets/portfolio-security-headers.conf;",
      `#     add_header Cache-Control "${cacheRules.assets}" always;`,
      "#   }",
      "#   location /images/ {",
      "#     include snippets/portfolio-security-headers.conf;",
      `#     add_header Cache-Control "${cacheRules.images}" always;`,
      "#   }",
      "#   location / {",
      "#     include snippets/portfolio-security-headers.conf;",
      `#     add_header Cache-Control "${cacheRules.html}" always;`,
      "#     try_files $uri $uri/ /index.html;",
      "#   }",
      "# }",
      "",
    ].join("\n"),

  caddy: () =>
    [
      `# ${stamp}`,
      "# Paste into the site's block in the Caddyfile (adjust the domain and root).",
      "SITE_DOMAIN {",
      "\troot * /var/www/personal-website/dist",
      "\tencode zstd gzip",
      "\tfile_server",
      "",
      "\theader {",
      ...entries.map(([name, value]) => `\t\t${name} "${value}"`),
      // "?" sets the header only when a more specific rule below has not.
      `\t\t?Cache-Control "${cacheRules.html}"`,
      "\t}",
      `\theader /assets/* Cache-Control "${cacheRules.assets}"`,
      `\theader /images/* Cache-Control "${cacheRules.images}"`,
      "}",
      "",
    ].join("\n"),
};

const plan = {
  cloudflare: { format: "_headers", target: "../../personal-website/public/_headers" },
  netlify: { format: "_headers", target: "../../personal-website/public/_headers" },
  vercel: { format: "vercel", target: "../../personal-website/vercel.json" },
  nginx: { format: "nginx" },
  caddy: { format: "caddy" },
}[host];

const output = formats[plan.format]();
if (flag("write")) {
  if (!plan.target) fail(`--write is not available for ${host}: paste the printed config into the server.`);
  const path = fileURLToPath(new URL(plan.target, import.meta.url));
  writeFileSync(path, output);
  console.error(`Wrote ${path} (CSP mode: ${mode})`);
} else {
  process.stdout.write(output);
}
